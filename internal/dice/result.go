package dice

import (
	"fmt"
	"strings"
)

// Result is the fully evaluated outcome of a dice expression.
//
// Field semantics (important for embedded consumers):
//   - Rolls holds the dice values AFTER the reroll pass but BEFORE
//     explosions. For most modifiers its length matches the original
//     dice count; for reroll-add it also includes the appended dice.
//     Explosions never appear here.
//   - Exploded holds only the additional dice produced by explosions.
//   - Kept is the final post-explode, post-keep/drop slice the total
//     is summed from.
//   - Total is the sum of Kept. Arithmetic operators (+ - * /) on the
//     surrounding expression are handled by the AST evaluator, not
//     reflected in Total of a sub-expression.
type Result struct {
	Expression string // original raw expression

	Rolls    []int // post-reroll values (pre-explode); see field doc above
	Rerolls  []int // values recorded by the reroll pass (replace tracks OLD, once tracks NEW)
	Exploded []int // additional values generated by explosions

	Kept    []int // values kept after explode + keep/drop (the slice Total sums)
	Dropped []int // values removed by keep/drop

	Total     int    // sum of Kept
	Successes int    // success threshold count (if any)
	Verbose   string // human-readable breakdown (filled in verbose.go)
}

// MultiRollResult represents N independent evaluations of the same expression.
// This is returned by Engine.RollMany.
type MultiRollResult struct {
	Expression string   `json:"expression"`
	Rolls      []Result `json:"rolls"`
	Summary    string   `json:"summary,omitempty"`
}

// FormatMultiExpression ensures a multi-roll expression is displayed with its
// `rolls=N` suffix exactly once.
func FormatMultiExpression(expr string, count int) string {
	expr = strings.TrimSpace(expr)
	if strings.Contains(expr, "rolls=") {
		return expr
	}
	if expr == "" {
		return fmt.Sprintf("rolls=%d", count)
	}
	return fmt.Sprintf("%s rolls=%d", expr, count)
}
